export function tr(
  lang: UiLanguage,
  key: string,
  params?: Record<string, string | number>
): string {
  const dict = TRANSLATIONS[lang] ?? TRANSLATIONS.En;
  let text = dict[key] ?? TRANSLATIONS.En[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function applyStaticI18n(lang: UiLanguage): void {
  document.documentElement.lang = LANG_HTML_ATTR[lang] ?? "en";
  document.title = tr(lang, "app.title");

  for (const el of Array.from(document.querySelectorAll<HTMLElement>("[data-i18n]"))) {
    const key = el.dataset.i18n;
    if (key) {
      el.textContent = tr(lang, key);
    }
  }
  for (const el of Array.from(document.querySelectorAll<HTMLElement>("[data-i18n-title]"))) {
    const key = el.dataset.i18nTitle;
    if (key) {
      el.setAttribute("title", tr(lang, key));
    }
  }
  for (const el of Array.from(document.querySelectorAll<HTMLElement>("[data-i18n-aria]"))) {
    const key = el.dataset.i18nAria;
    if (key) {
      el.setAttribute("aria-label", tr(lang, key));
    }
  }
  for (const el of Array.from(document.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]"))) {
    const key = el.dataset.i18nPlaceholder;
    if (key) {
      el.setAttribute("placeholder", tr(lang, key));
    }
  }
}
